FORBIDDEN_LETTERS = set('ьъыйё')


def get_required_letter(city_name: str) -> str:
    """Получить букву, на которую должен начинаться следующий город."""
    clean = city_name.replace('-', '').replace(' ', '').lower()
    for ch in reversed(clean):
        if ch.isalpha() and ch not in FORBIDDEN_LETTERS:
            return ch.upper()
    return clean[-1].upper()


def normalize(city: str) -> str:
    """Нормализовать название города для сравнения."""
    return city.strip().lower().replace('ё', 'е')


